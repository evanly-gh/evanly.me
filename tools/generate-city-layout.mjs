/**
 * generate-city-layout.mjs — precompute the deterministic city building layout.
 *
 * buildCityLayout() runs ~6s of seeded procedural packing + O(n²) clearance math
 * on the MAIN THREAD at page load (measured: it's the whole ~10s blank/blurry
 * gap before the first 3D frame). The layout is fully deterministic, so there's
 * no reason to recompute it in every visitor's browser — bake it once here and
 * ship it as data. cityLayout.ts loads this in production instead of computing.
 *
 * Run with: npm run assets:layout   (regenerate after changing any building-
 * layout code: cityLayout.ts, aboutReveal.ts, researchLayout.ts, roads.ts, etc.)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { computeCityLayout } from '../src/world/cityLayout.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SEED = 20260720; // must match buildCityLayout's default seed
const t0 = Date.now();
const layout = computeCityLayout(SEED);
const outPath = path.resolve(__dirname, '..', 'src', 'world', 'cityLayout.generated.ts');

const file = `// AUTO-GENERATED by tools/generate-city-layout.mjs — DO NOT EDIT BY HAND.
// Deterministic city building layout, precomputed at build time so the client
// skips the ~6s packing/clearance compute on load. Regenerate after changing any
// building-layout code with: npm run assets:layout
/* eslint-disable */
const PRECOMPUTED_CITY_LAYOUT = ${JSON.stringify(layout)};
export const PRECOMPUTED_CITY_LAYOUT_SEED = ${SEED};
export default PRECOMPUTED_CITY_LAYOUT;
`;

fs.writeFileSync(outPath, file, 'utf8');
console.log(
  `Wrote ${path.relative(path.resolve(__dirname, '..'), outPath)} — ` +
  `${layout.length} placements, ${(fs.statSync(outPath).size / 1024).toFixed(0)} KB, ` +
  `computed in ${Date.now() - t0}ms`,
);
